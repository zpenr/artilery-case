-- Таблицы:
--   Ranks - Звания
--   Users - пользователи (rank_id -> Ranks.id)
--   Equipments - типы оборудования (ДМК / ВР)
--   Parameters - параметры измерений
--   Logs - пачки измерений (Logs.user_id -> Users.id, Logs.parametr_id -> Parameters.id, Logs.equipment_id -> Equipments.id)


--Create tables
CREATE TABLE IF NOT EXISTS Users(id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
	name text, rank_id int);

CREATE TABLE IF NOT EXISTS Ranks(id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name text UNIQUE);

CREATE TABLE IF NOT EXISTS Parameters(id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	station_high int NOT NULL, 
	temperature float CHECK(temperature <= 58 AND temperature >= -58) NOT NULL, 
	pressure int CHECK(pressure <= 900 AND pressure >= 500) NOT NULL, 
	wind_direction int CHECK(wind_direction <= 59 AND wind_direction >= 0) NOT NULL, 
	wind_speed int CHECK(wind_speed <= 15 AND wind_speed >= 0) DEFAULT Null,
	bullet_drift int CHECK(bullet_drift <= 150 AND bullet_drift >= 0)  DEFAULT Null
	);

CREATE TABLE IF NOT EXISTS Equipments(id int GENERATED BY DEFAULT  AS IDENTITY PRIMARY KEY,
	name text UNIQUE);

CREATE TABLE IF NOT EXISTS Logs(id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id int NOT NULL, parametr_id int NOT NULL, 
	equipment_id int NOT NULL, date timestamp DEFAULT CURRENT_TIMESTAMP);

--Comments for Tables

COMMENT ON TABLE Ranks IS 'Список званий пользователей';
COMMENT ON TABLE Users IS 'Пользователи системы; rank_id ссылается на Ranks';
COMMENT ON TABLE Equipments IS 'Типы оборудования для измерений (ДМК, ВР)';
COMMENT ON TABLE Parameters IS 'Параметры измерений с диапазонами и единицами';
COMMENT ON TABLE Logs IS 'Пачки измерений; связывает пользователя, параметры и оборудование';

--Comments for Colums

--Parameters
COMMENT ON COLUMN Parameters.id IS 'Уникальный код параметров';

COMMENT ON COLUMN Parameters.station_high IS 'Целые числа. Высота метеопоста, м над уровнем моря';

COMMENT ON COLUMN Parameters.temperature  IS 'Дробные числа. Температура воздуха, °C';
COMMENT ON CONSTRAINT parameters_temperature_check ON Parameters IS 'Температура в пределах -58..58 °C';

COMMENT ON COLUMN Parameters.pressure IS 'Целые числа. Давление атмосферы, мм рт.ст.';
COMMENT ON CONSTRAINT parameters_pressure_check ON Parameters IS 'Давление в пределах 500..900 мм рт.ст.';

COMMENT ON COLUMN Parameters.wind_direction IS 'Целые числа. Направление ветра, деления угломера';
COMMENT ON CONSTRAINT parameters_wind_direction_check ON Parameters IS 'Направление ветра в пределах 0..59';

COMMENT ON COLUMN Parameters.wind_speed IS 'Целые числа. Скорость ветра, м/с, для ДМК';
COMMENT ON CONSTRAINT parameters_wind_speed_check ON Parameters IS 'Скорость ветра в пределах 0..15 м/с';

COMMENT ON COLUMN Parameters.bullet_drift IS 'Целые числа. Дальность сноса пуль, м, для ВР';
COMMENT ON CONSTRAINT parameters_bullet_drift_check ON Parameters IS 'Снос пуль в пределах 0..150 м';

--Users
COMMENT ON COLUMN Users.id IS 'Уникальный код пользователя';
COMMENT ON COLUMN Users.name IS 'ФИО пользователя';
COMMENT ON COLUMN Users.rank_id IS 'Звание (связь на Ranks.id)';

--Logs
COMMENT ON COLUMN Logs.id IS 'Уникальный код пачки измерений';
COMMENT ON COLUMN Logs.user_id IS 'Пользователь, выполнивший измерение';
COMMENT ON COLUMN Logs.parametr_id IS 'Параметры измерения';
COMMENT ON COLUMN Logs.equipment_id IS 'Использованное оборудование (ДМК/ВР)';
COMMENT ON COLUMN Logs.date IS 'Дата и время измерения (При отсутствии ставиться автоматически)';

--Ranks
COMMENT ON COLUMN Ranks.id IS 'Уникальный код звания';
COMMENT ON COLUMN Ranks.name IS 'Название звания';

--Equipments
COMMENT ON COLUMN Equipments.id IS 'Уникальный код оборудования';
COMMENT ON COLUMN Equipments.name IS 'Название оборудования';

