create table Measurment_input_params
(
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	log_id integer,
	param_id integer,
	units_id integer,
	value decimal
);

COMMENT ON TABLE Measurment_input_params IS 'Значения параметров измерения';

COMMENT ON COLUMN Measurment_input_params.id IS 'Уникальный код записи измерения';
COMMENT ON COLUMN Measurment_input_params.log_id IS 'Номер пачки измерения (связь с Logs.id)';
COMMENT ON COLUMN Measurment_input_params.param_id IS 'Тип параметра (связь с Types_parameters.id)';
COMMENT ON COLUMN Measurment_input_params.units_id IS 'Единица измерения значения (связь с Units_measurement.id)';
COMMENT ON COLUMN Measurment_input_params.value IS 'Числовое значение параметра';


