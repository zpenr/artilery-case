select Logs.date, Logs.id, Users.name, types_parameters.name, units_measurement.name, measurment_input_params.value
from types_parameters, units_measurement, Logs, measurment_input_params, Equipments, users, ranks
where
		measurment_input_params.param_id = types_parameters.id
	and measurment_input_params.units_id = units_measurement.id
	and Users.id = Logs.user_id
	and Users.rank_id = ranks.id
	and Equipments.id = Logs.equipment_id
	and measurment_input_params.log_id = Logs.id
	order by Logs.id;
	