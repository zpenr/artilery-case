FROM Logs
INNER JOIN Users ON Users.id = Logs.user_id
INNER JOIN Parameters ON Parameters.id = logs.parametr_id
INNER JOIN Equipments ON Equipments.id = logs.equipment_id
INNER JOIN Ranks ON Ranks.id = users.rank_id;